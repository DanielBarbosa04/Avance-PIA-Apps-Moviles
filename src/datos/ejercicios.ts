export function ejerciciosDeGrupo(grupo: GrupoId): Ejercicio[] {
  return NIVELES.flatMap((nivel) =>
    EJERCICIOS.filter((e) => e.grupo === grupo && e.nivel === nivel),
  );
}

export function buscarEjercicio(id: string): Ejercicio | undefined {
  return EJERCICIOS.find((e) => e.id === id);
}
